import Foundation

/// Глава утренней истории. Открывается только успешным утром.
struct StoryChapter: Identifiable, Equatable {
    let title: String
    let text: String

    var id: String { title }
}

/// Серия историй для своего направления: Фаджр — праведные халифы, спорт — бегуны и т. д.
struct StorySeries: Identifiable, Equatable {
    let module: WakeModule
    let title: String
    let subtitle: String
    let chapters: [StoryChapter]

    var id: String { module.rawValue }
}

/// «Утро-сериал»: каждое успешное утро открывает следующую главу серии своего направления.
/// Проспал — глава ждёт, пока снова встанешь.
enum StoryLibrary {
    static func series(for module: WakeModule) -> StorySeries {
        switch module {
        case .prayer: return caliphs
        case .sport: return runners
        case .study: return scholars
        case .work: return builders
        case .basic: return explorers
        }
    }

    /// Сколько успешных утр было в этом направлении: столько глав открыто.
    static func successCount(module: WakeModule, entries: [JournalEntry]) -> Int {
        entries.filter { $0.counts && $0.outcome == .success && ($0.module ?? .basic) == module }.count
    }

    static func unlockedCount(module: WakeModule, entries: [JournalEntry]) -> Int {
        min(successCount(module: module, entries: entries), series(for: module).chapters.count)
    }

    /// Глава, которую открыло это утро (номер с нуля), или nil, если серия уже прочитана.
    static func chapterOpened(module: WakeModule, entries: [JournalEntry]) -> Int? {
        let count = successCount(module: module, entries: entries)
        guard count >= 1, count <= series(for: module).chapters.count else { return nil }
        return count - 1
    }

