/// Данные оператора персональных данных. Подставляются во все документы. ЗАПОЛНИТЬ ДО ПУБЛИКАЦИИ.
enum LegalOperator {
    /// ФИО индивидуального предпринимателя или самозанятого либо наименование организации.
    static let name = "[ФИО или наименование оператора]"
    static let inn = "[ИНН]"
    static let address = "[адрес оператора]"
    /// Почта для обращений по персональным данным и отзыва согласий.
    static let email = "[почта для обращений]"
    /// Адрес публичной страницы с документами (нужен для App Store и для требования ст. 18.1 152-ФЗ).
    static let site = "[адрес сайта с документами]"

    static var isFilled: Bool {
        ![name, inn, address, email, site].contains { $0.hasPrefix("[") }
    }
}

enum LegalDocumentKind: String, CaseIterable, Identifiable {
    case terms, privacy, personalData, specialData, distribution

    var id: String { rawValue }

    var title: String {
        switch self {
        case .terms: return "Пользовательское соглашение"
        case .privacy: return "Политика конфиденциальности"
        case .personalData: return "Согласие на обработку персональных данных"
        case .specialData: return "Согласие на обработку данных о намазе"
        case .distribution: return "Согласие на распространение данных"
        }
    }
}

struct LegalSection: Identifiable {
    let id = UUID()
    let heading: String
    let paragraphs: [String]
}

struct LegalDocument {
    let kind: LegalDocumentKind
    let sections: [LegalSection]

    var title: String { kind.title }

    /// Весь текст одной строкой: по нему считается отпечаток принятой редакции.
    var plainText: String {
        ([title, "Редакция от \(LegalVersion.dateText)"] + sections.flatMap { [$0.heading] + $0.paragraphs }).joined(separator: "\n")
    }
}

